create table if not exists promotion_campaign_sightevent (
  id bigint generated by default as identity not null,
  promotion_campaign_id bigint not null,
  sightevent_id bigint not null,
  active boolean not null default true,
  source varchar(32) not null default 'MANUAL',
  source_tag_id bigint null,
  hpt_sight_event_id bigint null,
  hpt_atna_id bigint null,
  hpt_ticket_definition_id bigint null,
  hpt_ticket_pool_definition_id bigint null,
  ticket_pool_status varchar(32) not null default 'NOT_REQUIRED',
  created_at timestamp(6) not null default now(),
  updated_at timestamp(6) null,
  constraint promotion_campaign_sightevent_pkey primary key (id),
  constraint promotion_campaign_sightevent_unique
    unique (promotion_campaign_id, sightevent_id),
  constraint promotion_campaign_sightevent_source_check
    check (source in ('MANUAL', 'TAG')),
  constraint promotion_campaign_sightevent_source_tag_check
    check (source <> 'TAG' or source_tag_id is not null),
  constraint promotion_campaign_sightevent_pool_status_check
    check (ticket_pool_status in ('NOT_REQUIRED', 'NOT_CREATED', 'CONFIG_REQUIRED', 'CREATED', 'ERROR')),
  constraint promotion_campaign_sightevent_campaign_fk
    foreign key (promotion_campaign_id) references promotion_campaign(id),
  constraint promotion_campaign_sightevent_sightevent_fk
    foreign key (sightevent_id) references sightevent(id),
  constraint promotion_campaign_sightevent_source_tag_fk
    foreign key (source_tag_id) references tag(id)
);

