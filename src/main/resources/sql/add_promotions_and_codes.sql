create table if not exists promotion_code (
  id bigint generated by default as identity not null,
  promotion_campaign_id bigint not null,
  promotion_code_batch_id bigint null,
  code varchar(255) not null,
  code_type varchar(32) not null,
  status varchar(32) not null default 'ACTIVE',
  max_redemptions integer null,
  max_redemptions_per_customer integer null,
  max_redemptions_per_day integer null,
  reserved_redemptions_count integer not null default 0,
  used_redemptions_count integer not null default 0,
  reserved_until timestamp(6) null,
  created_at timestamp(6) not null default now(),
  updated_at timestamp(6) null,
  disabled_at timestamp(6) null,
  constraint promotion_code_pkey primary key (id),
  constraint promotion_code_code_key unique (code),
  constraint promotion_code_type_check
    check (code_type in ('ONE_TIME', 'FIXED')),
  constraint promotion_code_status_check
    check (status in ('ACTIVE', 'RESERVED', 'USED', 'DISABLED')),
  constraint promotion_code_fixed_status_check
    check (code_type <> 'FIXED' or status in ('ACTIVE', 'DISABLED')),
  constraint promotion_code_max_redemptions_check
    check (max_redemptions is null or max_redemptions > 0),
  constraint promotion_code_max_redemptions_customer_check
    check (max_redemptions_per_customer is null or max_redemptions_per_customer > 0),
  constraint promotion_code_max_redemptions_day_check
    check (max_redemptions_per_day is null or max_redemptions_per_day > 0),
  constraint promotion_code_reserved_count_check
    check (reserved_redemptions_count >= 0),
  constraint promotion_code_used_count_check
    check (used_redemptions_count >= 0),
  constraint promotion_code_one_time_limit_check
    check (code_type <> 'ONE_TIME' or max_redemptions is null or max_redemptions = 1),
  constraint promotion_code_campaign_fk
    foreign key (promotion_campaign_id) references promotion_campaign(id),
  constraint promotion_code_batch_fk
    foreign key (promotion_code_batch_id) references promotion_code_batch(id)
);

