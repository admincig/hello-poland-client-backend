alter table tag
  add column if not exists promotional boolean not null default false;

create table if not exists promotion_campaign (
  id bigint generated by default as identity not null,
  name varchar(255) not null,
  promotion_type varchar(32) not null,
  status varchar(32) not null default 'DRAFT',
  scope_type varchar(32) not null,
  valid_from timestamp(6) not null,
  valid_to timestamp(6) not null,
  global_limit integer null,
  code_limit integer null,
  customer_limit integer null,
  daily_limit integer null,
  required_ticket_quantity integer null,
  granted_ticket_quantity integer null,
  reserved_redemptions_count integer not null default 0,
  used_redemptions_count integer not null default 0,
  discount_percent numeric(5,2) null,
  discount_amount_gross integer null,
  created_at timestamp(6) not null default now(),
  updated_at timestamp(6) null,
  created_by bigint null,
  updated_by bigint null,
  constraint promotion_campaign_pkey primary key (id),
  constraint promotion_campaign_type_check
    check (promotion_type in ('TICKET', 'PERCENT', 'AMOUNT')),
  constraint promotion_campaign_status_check
    check (status in ('DRAFT', 'ACTIVE', 'DISABLED', 'ARCHIVED')),
  constraint promotion_campaign_scope_type_check
    check (scope_type in ('MANUAL', 'TAG', 'GLOBAL')),
  constraint promotion_campaign_dates_check
    check (valid_to >= valid_from),
  constraint promotion_campaign_ticket_not_global_check
    check (promotion_type <> 'TICKET' or scope_type <> 'GLOBAL'),
  constraint promotion_campaign_global_limit_check
    check (global_limit is null or global_limit > 0),
  constraint promotion_campaign_code_limit_check
    check (code_limit is null or code_limit > 0),
  constraint promotion_campaign_customer_limit_check
    check (customer_limit is null or customer_limit > 0),
  constraint promotion_campaign_daily_limit_check
    check (daily_limit is null or daily_limit > 0),
  constraint promotion_campaign_required_ticket_quantity_check
    check (required_ticket_quantity is null or required_ticket_quantity > 0),
  constraint promotion_campaign_granted_ticket_quantity_check
    check (granted_ticket_quantity is null or granted_ticket_quantity > 0),
  constraint promotion_campaign_reserved_count_check
    check (reserved_redemptions_count >= 0),
  constraint promotion_campaign_used_count_check
    check (used_redemptions_count >= 0),
  constraint promotion_campaign_discount_percent_check
    check (discount_percent is null or (discount_percent > 0 and discount_percent <= 100)),
  constraint promotion_campaign_discount_amount_check
    check (discount_amount_gross is null or discount_amount_gross > 0),
  constraint promotion_campaign_created_by_fk
    foreign key (created_by) references users(id),
  constraint promotion_campaign_updated_by_fk
    foreign key (updated_by) references users(id)
);

